#[tokio::test]
async fn small_profile_that_fits_request_body_is_rejected_before_confirmation_for_shared_reserve() {
    let dir = tempfile::tempdir().unwrap();
    let executor = Arc::new(SmallReserveExecutor(ControlledExecutor {
        root: dir.path().into(),
        prompts: Mutex::new(Vec::new()),
        requests: Mutex::new(Vec::new()),
    }));
    let runtime = OwnedParticipantRuntime::with_executor(
        dir.path().into(),
        Arc::new(ConnectionManager::new()),
        executor.clone(),
    );
    let mut configuration: RoundtableConfigV1 = serde_json::from_value(config()).unwrap();
    configuration.quotas.input_byte_limit = SafeInt(2_048);
    configuration.quotas.interjection_byte_limit = SafeInt(1);
    for participant in &mut configuration.participants {
        participant.model = Some(format!("fixture-model-{}", participant.ordinal));
    }
    for kind in [
        PhaseKind::Proposal,
        PhaseKind::Critique,
        PhaseKind::Synthesis,
    ] {
        let participant = &configuration.participants[0];
        let input = EncodedInputBounds {
            question: configuration.topic.clone(),
            role: participant.role.clone(),
            interjection: String::new(),
            evidence: String::new(),
            schema: result_schema(Some(kind)).to_string(),
            tools: service_tool_schema().into(),
            embedded: serde_json::to_string(&configuration).unwrap(),
        };
        let known = preflight_exact_prompt(&configuration, &input)
            .unwrap()
            .len() as u64;
        let required_request = 138_892 + 2 * known;
        eprintln!("small profile {kind:?}: K={known}, required_request={required_request}");
        assert!(known <= 28_858);
        assert!(
            required_request <= 196_608,
            "body cap fits; reserve must be the rejection"
        );
    }
    let error = runtime.preflight(&configuration).await.unwrap_err();
    assert_eq!(error.code, ErrorCode::ContextTooLarge);
    assert_eq!(error.details.reason.as_deref(), Some("context_too_large"));
    assert!(executor.0.requests.lock().unwrap().is_empty());
}

