struct HangingExecutor {
    started: tokio::sync::Notify,
    active: Mutex<Vec<IncarnationId>>,
    permissions: Mutex<Vec<Arc<ExecutionLease>>>,
    wait_cleanup: bool,
    cleanup_entered: tokio::sync::Notify,
    cleanup_release: tokio::sync::Notify,
    cancelled: std::sync::atomic::AtomicUsize,
    dropped: Arc<std::sync::atomic::AtomicUsize>,
    /// Synchronous work before the turn parks, standing in for a launch that
    /// blocks the room task (plan hashing, crun preparation).
    launch_block_ms: u64,
}
struct DroppedTurn(Arc<std::sync::atomic::AtomicUsize>);
impl Drop for DroppedTurn {
    fn drop(&mut self) {
        self.0.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    }
}
impl TokenBound for HangingExecutor {
    fn upper_bound(&self, bytes: &[u8]) -> RtResult<u64> {
        Ok(bytes.len() as u64)
    }
    fn capacity_tokens(&self) -> Option<u64> {
        Some(2_000_000)
    }
}
#[async_trait]
impl RoundtableTurnExecutor for HangingExecutor {
    fn request_envelope_bound_bytes(&self, participant: &ParticipantV1) -> RtResult<Option<u64>> {
        Ok(Some(fixture_request_envelope(participant)))
    }

    async fn capability(&self, _: &RoundtableConfigV1) -> RtResult<RuntimeCapability> {
        Ok(RuntimeCapability {
            recipients: json!([]),
            qualification_keys: json!([]),
            policy_hash: Hash256::from_bytes([2; 32]),
            profile: profile(),
        })
    }
    fn token_bound(&self) -> &(dyn TokenBound + Send + Sync) {
        self
    }
    async fn execute_turn(
        &self,
        request: RoundtableTurnRequest,
    ) -> RtResult<RoundtableTurnOutcome> {
        self.active.lock().unwrap().push(request.fence.incarnation);
        self.permissions.lock().unwrap().push(
            request
                .execution_lease
                .clone()
                .expect("production prepaid lease"),
        );
        let _drop = DroppedTurn(self.dropped.clone());
        if self.launch_block_ms > 0 {
            std::thread::sleep(std::time::Duration::from_millis(self.launch_block_ms));
        }
        self.started.notify_one();
        std::future::pending().await
    }
    async fn cancel_and_reap(&self, identity: RuntimeIdentity) -> RtResult<CleanupProof> {
        if self.wait_cleanup && self.cancelled.load(std::sync::atomic::Ordering::Relaxed) == 0 {
            self.cleanup_entered.notify_one();
            self.cleanup_release.notified().await;
        }
        let mut active = self.active.lock().unwrap();
        let index = active
            .iter()
            .position(|id| *id == identity.incarnation)
            .expect("known controlled incarnation");
        active.remove(index);
        self.cancelled
            .fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        Ok(proof(identity.incarnation))
    }
}
