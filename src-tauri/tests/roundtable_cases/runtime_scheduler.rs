#[derive(Clone, Copy)]
enum SchedulerGate {
    None,
    AcceptWriter,
    Completed,
    StaleCompleted,
    CompletedReadFailure,
}

async fn exercise_scheduler_gate(scenario: SchedulerGate) {
    let (dir, conn) = support::open_pool(5).await;
    migrate_roundtable(&conn).await.unwrap();
    let store = open_roundtable_store(conn.clone()).await.unwrap();
    let executor = Arc::new(ControlledExecutor {
        root: dir.path().into(),
        prompts: Mutex::new(Vec::new()),
        requests: Mutex::new(Vec::new()),
    });
    let runtime = Arc::new(OwnedParticipantRuntime::with_executor(
        dir.path().into(),
        Arc::new(ConnectionManager::new()),
        executor.clone(),
    ));
    let service = RoundtableService::open(
        ServiceConfig {
            data_dir: dir.path().into(),
            db_path: dir.path().join("roundtable.db"),
            db_identity: DbIdentity::new("runtime-scheduler").unwrap(),
            discover: None,
        },
        store.clone(),
        runtime.clone(),
    )
    .await
    .unwrap();
    let actor = ActorContext::from_trusted_entry(
        "00000000-0000-4000-8000-000000000001".parse().unwrap(),
        OperatorScope::SingleOperator,
        ClientIdentity {
            kind: ClientKind::Web,
            session_ref: "scheduler".into(),
        },
    );
    let config = config();
    let created = service
        .execute_fake_command(
            &actor,
            "roundtable_create",
            json!({"request_id":uuid::Uuid::new_v4().to_string(),"config":config}),
        )
        .await
        .unwrap();
    let room: RoomId = created["room_id"].as_str().unwrap().parse().unwrap();
    conn.execute_unprepared("UPDATE rt_rooms SET status='running'")
        .await
        .unwrap();
    let gate = match scenario {
        SchedulerGate::None => None,
        SchedulerGate::AcceptWriter => Some(store.arm_accept_writer_gate()),
        SchedulerGate::Completed
        | SchedulerGate::StaleCompleted
        | SchedulerGate::CompletedReadFailure => Some(store.arm_completed_run_gate()),
    };
    let completion_observation = matches!(scenario, SchedulerGate::StaleCompleted)
        .then(|| store.arm_completion_observation_gate());
    let release = gate.map(|gate| {
        let conn = conn.clone();
        let executor = executor.clone();
        tokio::spawn(async move {
            while !gate.is_waiting() {
                tokio::task::yield_now().await;
            }
            if let Some(observation) = completion_observation {
                // The monitor has observed budget_fence, but has not read the
                // terminal state yet. Order the epoch change before that read.
                while !observation.is_waiting() {
                    tokio::task::yield_now().await;
                }
                conn.execute_unprepared("UPDATE rt_rooms SET run_epoch=run_epoch+1")
                    .await
                    .unwrap();
                observation.release();
            }
            if matches!(scenario, SchedulerGate::AcceptWriter) {
                // Span a checkpoint while this scheduler owns the writer.
                tokio::time::sleep(std::time::Duration::from_millis(400)).await;
            } else {
                let permission = executor
                    .requests
                    .lock()
                    .unwrap()
                    .last()
                    .unwrap()
                    .execution_lease
                    .clone()
                    .unwrap();
                // Hold the scheduler until the monitor has actually observed
                // terminal state, rather than hoping a timer interleaves.
                tokio::time::timeout(std::time::Duration::from_secs(5), async {
                    while !permission.revoked() {
                        tokio::time::sleep(std::time::Duration::from_millis(10)).await;
                    }
                })
                .await
                .expect("the terminal-state checkpoint must revoke paid permission");
                if matches!(scenario, SchedulerGate::CompletedReadFailure) {
                    conn.execute_unprepared("UPDATE rt_messages SET body_json='invalid-json'")
                        .await
                        .unwrap();
                }
            }
            gate.release();
        })
    });
    let result = tokio::time::timeout(
        std::time::Duration::from_secs(5),
        runtime.run_room(store, room, serde_json::from_value(config).unwrap()),
    )
    .await
    .unwrap();
    if let Some(release) = release {
        release.await.unwrap();
    }
    if matches!(scenario, SchedulerGate::StaleCompleted) {
        let error = result.expect_err("a different run epoch must remain fenced");
        assert_eq!(error.details.reason.as_deref(), Some("budget_fence"));
        return;
    }
    if matches!(scenario, SchedulerGate::CompletedReadFailure) {
        let error = result.expect_err("terminal observation cannot replace the scheduler result");
        assert_eq!(error.code, ErrorCode::StorageUnavailable);
        assert_eq!(error.details.reason.as_deref(), Some("runtime_snapshot"));
        return;
    }
    result.expect("a healthy scheduler must finish across the checkpoint boundary");
    assert_eq!(
        support::scalar_i64(
            &conn,
            "SELECT COUNT(*) FROM rt_phases WHERE status='published'"
        )
        .await,
        2
    );
    assert_eq!(
        support::scalar_i64(&conn, "SELECT COUNT(*) FROM rt_messages").await,
        3
    );
    assert_eq!(
        support::scalar_i64(&conn, "SELECT COUNT(*) FROM rt_deliveries").await,
        3
    );
    assert_eq!(
        support::scalar_text(&conn, "SELECT status FROM rt_rooms").await,
        "completed"
    );
    assert_eq!(executor.prompts.lock().unwrap().len(), 3);
    assert_eq!(
        support::scalar_i64(
            &conn,
            "SELECT COUNT(*) FROM rt_speakers WHERE model_id='default'"
        )
        .await,
        0
    );
    assert_eq!(
        support::scalar_text(&conn, "SELECT model_id FROM rt_speakers WHERE ordinal=2").await,
        "fixture-model-0"
    );

    assert_eq!(support::scalar_i64(&conn,"SELECT COUNT(*) FROM rt_events WHERE cause NOT IN ('create','config','start','attempt','accept','close','publish','input','control','recovery','terminal')").await,0);
    assert!(!dir.path().join("roundtable/execution-policy.json").exists());
    let request = executor.requests.lock().unwrap()[0].clone();
    verify_pre_spawn_and_diagnostic_failure(&dir, &conn, request).await;
}

async fn verify_pre_spawn_and_diagnostic_failure(
    dir: &tempfile::TempDir,
    conn: &sea_orm::DatabaseConnection,
    request: RoundtableTurnRequest,
) {
    let rejected = rejected_live_executor_fixture(dir.path().into()).unwrap();
    let incarnation = request.fence.incarnation;
    let error = match rejected.execute_turn(request.clone()).await {
        Ok(_) => panic!("missing report cannot execute"),
        Err(error) => error,
    };
    assert_eq!(
        error.details.reason.as_deref(),
        Some("qualification_artifact_missing")
    );
    let cleanup = rejected
        .cancel_and_reap(RuntimeIdentity {
            incarnation,
            pid: 0,
        })
        .await
        .unwrap();
    assert_eq!(cleanup.process.incarnation, incarnation);
    assert!(cleanup.process.process_tree_empty && cleanup.tools_drained);
    assert!(rejected
        .cancel_and_reap(RuntimeIdentity {
            incarnation: uuid::Uuid::new_v4().to_string().parse().unwrap(),
            pid: 0
        })
        .await
        .is_err());
    let mut diagnostic = DiagnosticCapture::new(vec!["fixture-secret".into()]);
    diagnostic.push("prefix fixture-");
    diagnostic.push("secret suffix.");
    let capture = Mutex::new(Some(diagnostic));
    conn.execute_unprepared("CREATE TRIGGER diagnostic_fail BEFORE UPDATE OF diagnostic_ref ON rt_attempts BEGIN SELECT RAISE(ABORT,'fixture_diagnostic_write'); END").await.unwrap();
    assert!(persist_runtime_diagnostic_fixture(
        &request.store,
        request.room_id,
        request.fence.attempt_id,
        &capture
    )
    .await
    .is_err());
    assert!(capture.lock().unwrap().is_some());
    assert_eq!(
        support::scalar_i64(conn, "SELECT COUNT(*) FROM rt_diagnostics").await,
        0
    );
    conn.execute_unprepared("DROP TRIGGER diagnostic_fail")
        .await
        .unwrap();
    persist_runtime_diagnostic_fixture(
        &request.store,
        request.room_id,
        request.fence.attempt_id,
        &capture,
    )
    .await
    .unwrap();
    assert!(capture.lock().unwrap().is_none());
    assert_eq!(
        support::scalar_i64(conn, "SELECT COUNT(*) FROM rt_diagnostics").await,
        1
    );
    assert_eq!(
        support::scalar_text(conn, "SELECT assistant_prefix FROM rt_diagnostics").await,
        "prefix [redacted] suffix."
    );
}

